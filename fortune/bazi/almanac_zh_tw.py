def tw(s):
    """簡體 → 繁體：先整句查表，再逐字備援；list/dict 遞迴；非字串原樣回傳。"""
    if isinstance(s, list):
        return [tw(x) for x in s]
    if isinstance(s, dict):
        return {tw(k): tw(v) for k, v in s.items()}
    if not isinstance(s, str):
        return s
    if s in PHRASES:
        return PHRASES[s]
    return "".join(CHARS.get(ch, ch) for ch in s)
